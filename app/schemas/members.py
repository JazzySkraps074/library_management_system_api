"""Request and response schemas for the Member resource."""

from pydantic import BaseModel, ConfigDict, EmailStr, Field


class MemberBase(BaseModel):
    """Define fields shared by every Member schema."""

    # FastAPI uses these type hints and Field constraints in two ways:
    # 1. Pydantic validates request and response data at runtime.
    # 2. FastAPI adds the types and constraints to the OpenAPI document,
    #    which Swagger UI displays as API documentation.
    # Strip surrounding whitespace and reject JSON fields the model does not
    # define. These rules apply to every schema that inherits MemberBase.

    model_config = ConfigDict(
        extra="forbid",
        str_strip_whitespace=True,
    )

    name: str = Field(
        min_length=1,
        max_length=120,
        description="The name of the Member",
        examples=["John Smith"],
    )
    email: EmailStr = Field(
        min_length=1,
        max_length=255,
        description="The email address of the Member",
        examples=["jsmith123@example.com"],
    )
    membership_id: str = Field(
        max_length=1,
        description="The membership identifier of the Member",
        examples=["1"],
    )
    phone: str = Field(
        min_length=1,
        max_length=10,
        description="The phone number of the Member",
        examples=["1234567890"],
    )


class MemberCreate(MemberBase):
    """Validate the body used to create a Member."""


class MemberUpdate(MemberBase):
    """Validate the replacement body used to update a Member."""


class MemberResponse(BaseModel):
    """Describe a Member returned by the API."""

    # Pydantic can read values from SQLAlchemy model attributes, not only from
    # dictionaries. FastAPI uses this when it converts ORM objects to JSON.
    model_config = ConfigDict(from_attributes=True)

    # The server generates the ID, so it appears in responses but not in
    # MemberCreate or MemberUpdate request bodies.
    id: int = Field(
        gt=0,
        description="The unique identifier generated by the server.",
        examples=[1],
    )