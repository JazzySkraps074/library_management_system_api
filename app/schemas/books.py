"""Request and response schemas for the Book resource."""

from pydantic import BaseModel, ConfigDict, Field


class BookBase(BaseModel):
    """Define fields shared by every Book schema."""

    # These type hints and Field constraints validate data at runtime and also
    # become part of the OpenAPI contract displayed by Swagger UI.
    model_config = ConfigDict(
        extra="forbid",
        str_strip_whitespace=True,
    )

    title: str = Field(
        min_length=1,
        max_length=200,
        description="The title of the book.",
        examples=["Example Book"],
    )
    author: str = Field(
        min_length=1,
        max_length=120,
        description="The name of the author of the book.",
        examples=["Jane Smith"],
    )
    isbn: str = Field(
        min_length=1,
        max_length=13,
        description="The identifier number of the book.",
        examples=["1234567890123"],
    )
    published_year: int = Field(
        ge=1450,
        le=2026,
        description="The year the book was published.",
        examples=["1990"],
    )
    member_id: int = Field(
        gt=0,
        description="The identifier of the member that checked out this book.",
        examples=[1],
    )


class BookCreate(BookBase):
    """Validate the body used to create a Book."""


class BookUpdate(BookBase):
    """Validate the replacement body used to update a Book."""


class BookResponse(BookBase):
    """Describe a Book returned by the API."""

    # Allow FastAPI to serialize a SQLAlchemy Book object through this schema.
    model_config = ConfigDict(from_attributes=True)

    id: int = Field(
        gt=0,
        description="The unique identifier generated by the server.",
        examples=[1],
    )